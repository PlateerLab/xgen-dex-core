// afterPack — ad-hoc code-sign the macOS .app.
//
// The connector ships UN-notarized (no paid Apple Developer ID yet). On Apple
// Silicon an *unsigned* app is hard-blocked at launch with "손상되었기 때문에
// 열 수 없습니다 — 휴지통으로 이동" (right-click → Open does NOT bypass it). An
// *ad-hoc* signature is a valid signature for execution, so Gatekeeper
// downgrades that to the bypassable "확인되지 않은 개발자" prompt, and the
// `xattr -dr com.apple.quarantine` escape hatch always works.
//
// When a real Developer ID is configured (CSC_LINK / CSC_IDENTITY present),
// electron-builder already signs properly — skip the ad-hoc pass so we don't
// clobber it. Notarization can then layer on via @electron/notarize.
const { execFileSync } = require('node:child_process');
const path = require('node:path');

const fs = require('node:fs');

/** Keep only the native helper(s) that can run in this artifact. The npm
 * package contains every OS binary; shipping all of them adds ~55MB and makes
 * code-signing/auditing needlessly broad. Linux keeps glibc+musl for the target
 * arch because the package format may run on either libc. */
function pruneAgentBrowser(context) {
  const platform = context.electronPlatformName;
  const archNames = { 1: 'x64', 3: 'arm64', 4: 'universal' };
  const arch = archNames[context.arch] || 'x64';
  const appName = context.packager.appInfo.productFilename;
  const resources =
    platform === 'darwin'
      ? path.join(context.appOutDir, `${appName}.app`, 'Contents', 'Resources')
      : path.join(context.appOutDir, 'resources');
  const binDir = path.join(resources, 'app.asar.unpacked', 'node_modules', 'agent-browser', 'bin');
  if (!fs.existsSync(binDir)) throw new Error(`agent-browser package missing: ${binDir}`);
  const arches = arch === 'universal' ? ['arm64', 'x64'] : [arch];
  const allowed = new Set(['agent-browser.js', '.install-method']);
  for (const cpu of arches) {
    if (platform === 'linux') {
      allowed.add(`agent-browser-linux-${cpu}`);
      allowed.add(`agent-browser-linux-musl-${cpu}`);
    } else if (platform === 'darwin') {
      allowed.add(`agent-browser-darwin-${cpu}`);
    } else if (platform === 'win32') {
      allowed.add(`agent-browser-win32-${cpu}.exe`);
    }
  }
  for (const name of fs.readdirSync(binDir)) {
    if (name.startsWith('agent-browser-') && !allowed.has(name)) {
      fs.rmSync(path.join(binDir, name), { force: true });
    }
  }
  for (const name of allowed) {
    const file = path.join(binDir, name);
    if (fs.existsSync(file) && platform !== 'win32') fs.chmodSync(file, 0o755);
  }
  console.log(`[afterPack] agent-browser ${platform}/${arch}: ${[...allowed].join(', ')}`);
}

// Linux launcher shim (geny-connector 이식). Chromium's zygote + SUID-sandbox
// helper check run BEFORE any app JS (appendSwitch('no-sandbox') in the main
// module is already too late), so the only place to decide "can this machine
// sandbox?" is a wrapper that execs the real binary.
//
// Ubuntu 23.10+/24.04 sets kernel.apparmor_restrict_unprivileged_userns=1,
// which blocks the namespace sandbox for unprivileged processes. The deb
// installs a SUID-root chrome-sandbox (build/linux-after-install.tpl) so the
// SUID fallback works — but an AppImage mounts as the user and CANNOT carry a
// SUID helper, and Chromium then dies with SIGTRAP at launch. The shim passes
// --no-sandbox ONLY in that no-sandbox-possible case (userns restricted AND
// no SUID-root helper); everywhere else the full sandbox stays on.
function wrapLinuxExecutable(context) {
  const exe = context.packager.executableName;
  const exePath = path.join(context.appOutDir, exe);
  const realName = `${exe}.bin`;
  fs.renameSync(exePath, path.join(context.appOutDir, realName));
  // 시임의 판단은 **추정**이다: SUID 비트가 있어도 실제로 샌드박스가 서지
  // 않는 경우가 있다 (24.04 실기에서 확인 — 크래시 cmdline 에 --no-sandbox 가
  // 없는 채 SIGTRAP). 비트만 보고 결정하면 그 경우를 영영 못 넘는다.
  //
  // 그래서 **실행해 보고 되돌린다**: 기동 직후(짧은 시간 안에) SIGTRAP(133)
  // 으로 죽으면 샌드박스가 원인이므로 --no-sandbox 로 한 번 재시도한다.
  // 오래 돌다가 난 SIGTRAP 은 진짜 버그이므로 재시도하지 않는다.
  const shim = `#!/bin/bash
# Generated by build/afterPack.cjs — sandbox-capability launcher shim.
DIR="$(dirname "$(readlink -f "$0")")"
REAL="$DIR/${realName}"

has_flag() { case " $* " in *" --no-sandbox "*) return 0 ;; esac; return 1; }

# 사전 판단(싸다): userns 가 막혀 있고 SUID-root 헬퍼도 없으면 확실히 불가능.
needs_no_sandbox() {
  has_flag "$@" && return 1
  # 설치 경로에 공백이 있으면 zygote 가 자기 자신을 재실행할 때 그 지점에서
  # 잘려 죽는다 (실기: "failed to execvp: /opt/XGEN"). productName 에서 공백을
  # 없앴지만, 사용자가 다른 경로에 풀어 쓰는 경우(AppImage 등)까지 대비한다.
  case "$DIR" in *" "*) return 0 ;; esac
  [ "$(cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>/dev/null)" = "1" ] || return 1
  [ -u "$DIR/chrome-sandbox" ] && [ "$(stat -c %u "$DIR/chrome-sandbox" 2>/dev/null)" = "0" ] && return 1
  return 0
}

if needs_no_sandbox "$@"; then
  exec -a "$0" "$REAL" --no-sandbox "$@"
fi

# 사전 판단이 "괜찮다"고 해도 실제로는 실패할 수 있다 — 결과를 보고 되돌린다.
START=$(date +%s)
"$REAL" "$@"
STATUS=$?
ELAPSED=$(( $(date +%s) - START ))
# 133 = 128 + SIGTRAP(5). 기동 직후면 샌드박스가 원인이다.
if [ "$STATUS" -eq 133 ] && [ "$ELAPSED" -le 10 ] && ! has_flag "$@"; then
  echo "xgen-dex: sandbox unavailable (SIGTRAP at startup) - retrying with --no-sandbox" >&2
  exec -a "$0" "$REAL" --no-sandbox "$@"
fi
exit $STATUS
`;
  fs.writeFileSync(exePath, shim, { mode: 0o755 });
  console.log(`[afterPack] linux sandbox shim: ${exe} -> ${realName}`);
}

module.exports = async function afterPack(context) {
  pruneAgentBrowser(context);
  if (context.electronPlatformName === 'linux') {
    wrapLinuxExecutable(context);
    return;
  }
  if (context.electronPlatformName !== 'darwin') return;
  if (process.env.CSC_LINK || process.env.CSC_IDENTITY) return;

  const appName = context.packager.appInfo.productFilename;
  const appPath = path.join(context.appOutDir, `${appName}.app`);
  console.log(`[afterPack] ad-hoc signing ${appPath}`);
  // --deep so the nested Electron Framework + Helper bundles are covered.
  execFileSync('codesign', ['--force', '--deep', '--sign', '-', appPath], {
    stdio: 'inherit',
  });
  console.log('[afterPack] ad-hoc signature applied');
};
